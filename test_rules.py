import sync
from ocr import match_screen, normalize

cfg = sync.load_cfg()
rules = cfg["rules"]
flow = cfg.get("flow", {}) or {}
fscreens = flow.get("screens") or []


def judge(text, counts=None, force=None):
    n = normalize(text)
    fidx = sum((counts or {}).get(s, 0) for s in fscreens)
    sc = match_screen(n, rules, {"force": force, "flow": flow,
                                 "flow_index": fidx, "counts": counts or {}})
    targets = [sc] if sc else []
    if (sc in fscreens and flow.get("enabled") and
            flow.get("mode", "duplicate_first") == "duplicate_first" and fidx == 0):
        # 第 2 张图：带「收起」= 确定是第二屏，只写第二屏；没有收起 -> 第二屏+第三屏都写
        skip = [normalize(w) for w in (flow.get("skip_duplicate_if") or [])]
        targets = [fscreens[0]] if (skip and any(w and w in n for w in skip)) else list(fscreens)
    return sc, targets


